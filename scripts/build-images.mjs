/**
 * Builds responsive AVIF + WebP image sets and a typed manifest with
 * tiny blur placeholders (LQIP).
 *
 *   npm run images          – download missing sources + build
 *   npm run images -- --force   – rebuild everything
 *
 * Sources are cached in assets-src/. A file named assets-src/<key>.jpg
 * (e.g. your own photo) always wins over the downloaded Unsplash source.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import { IMAGES } from './images.config.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC_DIR = path.join(ROOT, 'assets-src');
const CACHE_DIR = path.join(SRC_DIR, '_unsplash');
const OUT_DIR = path.join(ROOT, 'public', 'img');
const MANIFEST = path.join(ROOT, 'src', 'data', 'images.generated.ts');
const FORCE = process.argv.includes('--force');

await fs.mkdir(CACHE_DIR, { recursive: true });
await fs.mkdir(OUT_DIR, { recursive: true });

const exists = (p) => fs.access(p).then(() => true, () => false);

async function sourceFor(key, id) {
  const own = path.join(SRC_DIR, `${key}.jpg`);
  if (await exists(own)) return own;
  const cached = path.join(CACHE_DIR, `${id}.jpg`);
  if (!(await exists(cached))) {
    const url = `https://images.unsplash.com/photo-${id}?w=2400&q=88&fm=jpg`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`Download failed ${res.status} for ${key}`);
    await fs.writeFile(cached, Buffer.from(await res.arrayBuffer()));
    console.log(`  ↓ ${key}`);
  }
  return cached;
}

async function pipelineFor(src, cfg) {
  const meta = await sharp(src).metadata();
  let { width: W, height: H } = meta;
  let region = { left: 0, top: 0, width: W, height: H };
  if (cfg.zoom) {
    const w = Math.round(W / cfg.zoom), h = Math.round(H / cfg.zoom);
    region = { left: Math.round((W - w) / 2), top: Math.round((H - h) / 2), width: w, height: h };
  }
  const aspect = cfg.aspect ?? region.width / region.height;
  return { region, aspect };
}

const manifest = {};
const entries = Object.entries(IMAGES);
let built = 0;

for (const [key, cfg] of entries) {
  const src = await sourceFor(key, cfg.id);
  const { region, aspect } = await pipelineFor(src, cfg);
  const base = () => sharp(src).extract(region);
  const position = cfg.focus ?? 'centre';

  for (const w of cfg.widths) {
    const h = Math.round(w / aspect);
    const avif = path.join(OUT_DIR, `${key}-${w}.avif`);
    const webp = path.join(OUT_DIR, `${key}-${w}.webp`);
    if (!FORCE && (await exists(avif)) && (await exists(webp))) continue;
    const resized = base().resize(w, h, { fit: 'cover', position });
    await Promise.all([
      resized.clone().avif({ quality: 50, effort: 4 }).toFile(avif),
      resized.clone().webp({ quality: 74 }).toFile(webp),
    ]);
    built++;
  }

  const lqip = await base()
    .resize(24, Math.round(24 / aspect), { fit: 'cover', position })
    .webp({ quality: 40 })
    .toBuffer();

  manifest[key] = {
    widths: cfg.widths,
    aspect: Number(aspect.toFixed(4)),
    lqip: `data:image/webp;base64,${lqip.toString('base64')}`,
  };
  process.stdout.write('.');
}

const ts = `// AUTO-GENERATED by scripts/build-images.mjs — do not edit by hand.
export type ImageKey = ${Object.keys(manifest).map((k) => `'${k}'`).join(' | ')};

export interface ImageMeta {
  widths: number[];
  aspect: number;
  lqip: string;
}

export const IMAGE_META: Record<ImageKey, ImageMeta> = ${JSON.stringify(manifest, null, 2)};
`;
await fs.writeFile(MANIFEST, ts);
console.log(`\nDone. ${built} size variants built, ${entries.length} images in manifest.`);
